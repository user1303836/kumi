//! The API table build.rs generates is the vendored header's, every function of it, and sdk/SOURCE.txt says truly what
//! was vendored. A newer header needs only the two files and the note replaced: CI's Extended run builds the newest
//! upstream header each week and runs the first test here against it.

use reaper_kumi::api::{FUNCTIONS, FUNCTION_COUNT, SDK_VERSION};
use std::collections::BTreeSet;
use std::path::Path;

fn sdk_bytes(name: &str) -> Vec<u8> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("sdk").join(name);
    std::fs::read(&path).unwrap_or_else(|error| panic!("{}: {error}", path.display()))
}

fn sdk(name: &str) -> String {
    String::from_utf8(sdk_bytes(name)).unwrap()
}

/// The functions REAPERAPI_LoadAPI's table names, read apart from build.rs's parser.
fn listed(header: &str) -> Vec<String> {
    header
        .lines()
        .filter_map(|line| line.trim_start().strip_prefix("{(void**)&REAPERAPI_FUNCNAME("))
        .map(|rest| rest.split(')').next().unwrap().to_string())
        .collect()
}

#[test]
fn the_generated_table_is_the_headers_every_function() {
    let header = sdk("reaper_plugin_functions.h");
    let listed = listed(&header);
    let generated: Vec<String> = FUNCTIONS.iter().map(|f| f.name.to_str().unwrap().to_string()).collect();
    assert_eq!(FUNCTION_COUNT, generated.len());
    assert_eq!(generated.len(), listed.len(), "the header lists {} functions, the table has {}", listed.len(), generated.len());
    let (generated, listed): (BTreeSet<_>, BTreeSet<_>) = (generated.into_iter().collect(), listed.into_iter().collect());
    assert_eq!(generated, listed);
    assert!(header.contains(&format!("Generated by REAPER v{SDK_VERSION}")), "SDK_VERSION {SDK_VERSION} isn't the header's");
}

#[test]
fn source_txt_names_the_vendored_headers_hashes_version_and_count() {
    let note = sdk("SOURCE.txt");
    for name in ["reaper_plugin_functions.h", "reaper_plugin.h"] {
        let sha = daw_bridge::auth::sha256_hex(&sdk_bytes(name));
        let line = note.lines().skip_while(|line| !line.starts_with(&format!("- {name}"))).nth(1).unwrap_or_default();
        assert_eq!(line.trim(), format!("sha256 {sha}"), "SOURCE.txt's hash for {name}: replace the note with the header");
    }
    let named = format!("(\"Generated by REAPER v{SDK_VERSION}\", {FUNCTION_COUNT} functions)");
    assert!(note.contains(&named), "SOURCE.txt doesn't say {named}");
    assert!(note.contains(&format!("\"sdk {SDK_VERSION}\"")), "SOURCE.txt doesn't name the SDK commit for {SDK_VERSION}");
}
