//! Renoise 3.5.4's native devices, as measured in the lab (the M4 n-devices notes): each one's path name, XML type and
//! parameters in Renoise's order, with the XML element that saves each (none for a trigger Renoise doesn't save) and its
//! range, default and step (0: continuous). Generated from the lab's inventory; the names are the defaults (some follow
//! the device: EQ 5's gains name their frequency, a Splitter's lane gains its type, a Doofer's macros their names).

pub use crate::renoise::texts::Text;

/// One parameter: its name, the XML element it is saved in ("" when Renoise doesn't save it), range, default and step.
pub struct Param {
    pub name: &'static str,
    pub element: &'static str,
    pub min: f64,
    pub max: f64,
    pub default: f64,
    pub step: f64,
    /// How its value reads as text (and text as a value).
    pub text: Text,
}

/// One native device: the last part of its path ("EQ 5"), its XML type ("Eq5Device"), its parameters, and whether it
/// may go inside a Doofer or Splitter (routing devices may not: Renoise crashed on them there).
pub struct Device {
    pub name: &'static str,
    pub xml: &'static str,
    pub params: &'static [Param],
    pub nests: bool,
}

const fn p(name: &'static str, element: &'static str, min: f64, max: f64, default: f64, step: f64, text: Text) -> Param {
    Param { name, element, min, max, default, step, text }
}

