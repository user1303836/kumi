/// The native device of this XML type.
pub fn by_xml(xml: &str) -> Option<&'static Device> {
    DEVICES.iter().find(|device| device.xml == xml)
}

/// The native device of this name (the last part of its path, any case).
pub fn by_name(name: &str) -> Option<&'static Device> {
    DEVICES.iter().find(|device| device.name.eq_ignore_ascii_case(name))
}

/// How parameter k (from 1) of the native device of this XML type reads as text.
pub fn text_of(xml: &str, k: usize) -> Option<&'static Text> {
    by_xml(xml).and_then(|device| device.params.get(k.checked_sub(1)?)).map(|param| &param.text)
}
